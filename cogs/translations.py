# Default language
DEFAULT_LANGUAGE = 'en'

# User language preferences (stored in memory, could be persisted to DB)
user_languages = {}

def get_text(key: str, lang: str = None, **kwargs) -> str:
    """Get translated text for a key.
    
    Args:
        key: Translation key
        lang: Language code (default: English)
        **kwargs: Format arguments for the string
        
    Returns:
        Translated and formatted text
    """
    if lang is None:
        lang = DEFAULT_LANGUAGE
    
    # Fallback to English if language not found
    if lang not in TRANSLATIONS:
        lang = DEFAULT_LANGUAGE
    
    # Get translation, fallback to English, then to key itself
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS.get(DEFAULT_LANGUAGE, {}).get(key, key)
    
    # Format with kwargs if provided
    if kwargs:
        try:
            return text.format(**kwargs)
        except:
            return text
    
    return text

def set_user_language(user_id: int, language: str):
    """Set language preference for a user."""
    user_languages[user_id] = language

def get_user_language(user_id: int) -> str:
    """Get language preference for a user."""
    return user_languages.get(user_id, DEFAULT_LANGUAGE)

